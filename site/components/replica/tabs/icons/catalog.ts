export const catalog: IconEntry[] = list.map(([name, icon, tags = ""]) => ({ name, icon, tags: tags.split(" ") }));

/** `arrow-right` → `ArrowRight`, the component's name for the JSX copy. */
export function componentName(name: string): string {
  return name
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

/**
 * The matches, best first (LucideIndex.search): the exact name, names that start with
 * the query, a name part that starts with it, names that contain it, every word in a
 * name part, then tags. Ties go to the shorter name, then A to Z.
 */
export function searchIcons(query: string): IconEntry[] {
  const words = query
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .split(/[^\p{L}\p{N}]+/u)
    .filter(Boolean);
  if (words.length === 0) return [];
  const slug = words.join("-");
  const compact = words.join("");
  const phrase = words.join(" ");
  const score = (entry: IconEntry): number | null => {
    const name = entry.name;
    const parts = name.split("-");
    if (name === slug || name.replaceAll("-", "") === compact) return 0;
    if (name.startsWith(slug) || name.replaceAll("-", "").startsWith(compact)) return 1;
    if (name.includes(`-${slug}`)) return 2;
    if (name.includes(slug)) return 3;
    if (words.length > 1 && words.every((word) => parts.some((part) => part.startsWith(word)))) return 5;
    if (entry.tags.includes(phrase)) return 6;
    if (entry.tags.some((tag) => tag.startsWith(phrase))) return 7;
    if (words.every((word) => parts.some((part) => part.startsWith(word)) || entry.tags.some((tag) => tag.startsWith(word)))) return 8;
    if (phrase.length >= 3 && entry.tags.some((tag) => tag.includes(phrase))) return 9;
    return null;
  };
  return catalog
    .map((entry, index) => ({ entry, index, value: score(entry) }))
    .filter((match): match is { entry: IconEntry; index: number; value: number } => match.value !== null)
    .sort((a, b) => a.value - b.value || a.entry.name.length - b.entry.name.length || a.index - b.index)
    .map(({ entry }) => entry);
}
