import AppKit
import ApplicationServices
import CleenKit
import CryptoKit
import Observation

/// Clipboard history: watches the pasteboard, keeps the last 300 copies on disk, and
/// pastes one back into the app you were in.
///
/// Password managers mark secrets as concealed or transient (nspasteboard.org); those
/// copies are never recorded.
@Observable
final class ClipboardModel {
    static let enabledKey = "clipboardHistoryEnabled"

    private(set) var log = ClipboardLog()
    var query = ""
    var kind: ClipboardEntry.Kind?
    var selectedID: UUID?

    /// Receives the PNG of a screenshot taken straight to the clipboard (⌃⌘⇧3/4).
    @ObservationIgnored var onScreenshot: (Data) -> Void = { _ in }
    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var watcher: Task<Void, Never>?
    @ObservationIgnored private let folder = URL.applicationSupportDirectory.appending(path: "app.cleen.Cleen/Clipboard", directoryHint: .isDirectory)
    @ObservationIgnored private var saveTask: Task<Void, Never>?

    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    init() {
        UserDefaults.standard.register(defaults: [Self.enabledKey: true])
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        if let data = try? Data(contentsOf: folder.appending(path: "history.json")),
           let saved = try? JSONDecoder().decode(ClipboardLog.self, from: data) {
            log = saved
        }
    }

    var isEnabled: Bool { UserDefaults.standard.bool(forKey: Self.enabledKey) }

    /// What the list shows: filtered by type and search, newest first.
    var visible: [ClipboardEntry] {
        let matching = log.entries.filter { (kind == nil || $0.kind == kind) && $0.matches(query) }
        return matching.filter(\.pinned) + matching.filter { !$0.pinned }
    }

    var selected: ClipboardEntry? {
        let entries = visible
        return entries.first { $0.id == selectedID } ?? entries.first
    }

    func imageURL(for entry: ClipboardEntry) -> URL? {
        entry.imageFile.map { folder.appending(path: $0) }
    }

    // MARK: Watching

    /// Polls the pasteboard's change count; it's the only signal macOS offers, and
    /// reading one integer twice a second costs nothing.
    func start() {
        guard watcher == nil else { return }
        watcher = Task { [weak self] in
            while !Task.isCancelled {
                self?.check()
                try? await Task.sleep(for: .milliseconds(500))
            }
        }
    }

    private func check() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard isEnabled else { return }
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        let source = NSWorkspace.shared.frontmostApplication
        guard source?.bundleIdentifier != Bundle.main.bundleIdentifier else { return }
        guard let entry = capture(pasteboard, source: source) else { return }
        let dropped = log.record(entry)
        deleteFiles(of: dropped)
        scheduleSave()
    }

    private func capture(_ pasteboard: NSPasteboard, source: NSRunningApplication?) -> ClipboardEntry? {
        let bundleID = source?.bundleIdentifier
        let name = source?.localizedName

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map { $0.path(percentEncoded: false) }
            let joined = paths.joined(separator: "\n")
            return ClipboardEntry(kind: .files, text: joined, files: paths, byteCount: joined.utf8.count, contentHash: Self.hash(Data(joined.utf8)), sourceBundleID: bundleID, sourceName: name)
        }
        if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff), let image = NSImage(data: data),
           let png = Self.pngData(image) {
            let hash = Self.hash(png)
            let file = "\(hash.prefix(24)).png"
            try? png.write(to: folder.appending(path: file), options: .atomic)
            let pixels = image.representations.first.map { ($0.pixelsWide, $0.pixelsHigh) } ?? (Int(image.size.width), Int(image.size.height))
            // The capture service is alive while a ⌃ screenshot lands on the clipboard.
            if !NSRunningApplication.runningApplications(withBundleIdentifier: "com.apple.screencaptureui").isEmpty {
                onScreenshot(png)
            }
            return ClipboardEntry(kind: .image, imageFile: file, imageWidth: pixels.0, imageHeight: pixels.1, byteCount: png.count, contentHash: hash, sourceBundleID: bundleID, sourceName: name)
        }
        if let string = pasteboard.string(forType: .string), !string.isEmpty {
            let text = String(string.prefix(100_000))
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            let isLink = !trimmed.contains(" ") && !trimmed.contains("\n")
                && (URL(string: trimmed)?.scheme.map { ["http", "https"].contains($0) } ?? false)
            return ClipboardEntry(kind: isLink ? .link : .text, text: text, byteCount: text.utf8.count, contentHash: Self.hash(Data(text.utf8)), sourceBundleID: bundleID, sourceName: name)
        }
        return nil
    }

    // MARK: Actions

    /// Puts the entry back on the clipboard.
    func copy(_ entry: ClipboardEntry) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch entry.kind {
        case .text, .link:
            pasteboard.setString(entry.text ?? "", forType: .string)
        case .image:
            if let url = imageURL(for: entry), let data = try? Data(contentsOf: url) {
                pasteboard.setData(data, forType: .png)
            }
        case .files:
            pasteboard.writeObjects((entry.files ?? []).map { URL(filePath: $0) as NSURL })
        }
        // Our own write must not come back as a new entry.
        lastChangeCount = pasteboard.changeCount
        log.touch(entry.id)
        scheduleSave()
    }

    /// Copies, then sends ⌘V to the app that's in front (the notch never takes focus).
    /// Without Accessibility permission it asks for it once and leaves the copy in place.
    @discardableResult
    func paste(_ entry: ClipboardEntry) -> Bool {
        copy(entry)
        let trusted = AXIsProcessTrustedWithOptions(["AXTrustedCheckOptionPrompt": true] as CFDictionary)
        guard trusted else { return false }
        let source = CGEventSource(stateID: .combinedSessionState)
        let keyV: CGKeyCode = 9
        let down = CGEvent(keyboardEventSource: source, virtualKey: keyV, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: keyV, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
        return true
    }

    func togglePin(_ entry: ClipboardEntry) {
        log.togglePin(entry.id)
        scheduleSave()
    }

    func delete(_ entry: ClipboardEntry) {
        if let removed = log.remove(entry.id) { deleteFiles(of: [removed]) }
        scheduleSave()
    }

    func clear() {
        deleteFiles(of: log.removeAll())
        scheduleSave()
    }

    /// Moves the selection with the arrow keys.
    func moveSelection(by offset: Int) {
        let entries = visible
        guard !entries.isEmpty else { return }
        let current = entries.firstIndex { $0.id == selected?.id } ?? 0
        selectedID = entries[min(max(0, current + offset), entries.count - 1)].id
    }

    // MARK: Storage

    private func deleteFiles(of entries: [ClipboardEntry]) {
        let stillUsed = Set(log.entries.compactMap(\.imageFile))
        for file in entries.compactMap(\.imageFile) where !stillUsed.contains(file) {
            try? FileManager.default.removeItem(at: folder.appending(path: file))
        }
    }

    private func scheduleSave() {
        saveTask?.cancel()
        let log = log
        let url = folder.appending(path: "history.json")
        saveTask = Task {
            try? await Task.sleep(for: .seconds(1))
            guard !Task.isCancelled, let data = try? JSONEncoder().encode(log) else { return }
            try? data.write(to: url, options: .atomic)
        }
    }

    private static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).map { ($0 < 16 ? "0" : "") + String($0, radix: 16) }.joined()
    }

    private static func pngData(_ image: NSImage) -> Data? {
        guard let tiff = image.tiffRepresentation, let bitmap = NSBitmapImageRep(data: tiff) else { return nil }
        return bitmap.representation(using: .png, properties: [:])
    }
}
